package com.miniagent.agent.scope;

/**
 * 本轮相对上一轮的任务边界转移。三个取值，互斥且覆盖全部情况。
 *
 * <h2>为什么是三个而不是两个</h2>
 *
 * <p>「沿用当前任务」和「开新任务」这两个好理解；容易漏掉的是第三个
 * ——<b>回到被挂起的那个任务</b>。用户说「继续」时，当前任务已经不是他要做的那个了：
 * 上一次切任务时，旧任务被挂起、当前指针移到了新任务上。如果只有「沿用/新开」两种，
 * 「继续」只能「沿用」，于是它查的是新任务的槽位，捞得到清单却捞不到图。</p>
 *
 * <p>所以「回到被挂起的任务」必须是独立的一步。{@link #NEW} 与 {@link #RESUME} 是一对互逆操作：
 * {@code NEW} 把当前任务放到「刚离开」的位置并开一个新的，{@code RESUME} 把它换回来。
 * 被离开的任务一直保留自己的状态，所以来回切不会串台。</p>
 */
public enum TaskBoundary {

    /** 边界没动：同一个任务里继续下一轮。 */
    SAME,

    /** 开了新任务：上一任务的工作集已被释放（挂起或归档）。 */
    NEW,

    /** 回到被挂起的任务：用户明确要求接着做上一个任务。 */
    RESUME
}
