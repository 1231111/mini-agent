package com.miniagent.migration;

import org.flywaydb.core.api.migration.Context;
import org.junit.jupiter.api.Test;

import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.ResultSet;
import java.sql.Statement;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

class TaskScopedEpisodesMigrationTest {

    @Test
    void addsNullableTaskIdAndUniqueIndexWithoutChangingLegacyRows() throws Exception {
        try (Connection connection = DriverManager.getConnection(
                "jdbc:h2:mem:task-episodes-migration;DB_CLOSE_DELAY=-1")) {
            try (Statement statement = connection.createStatement()) {
                statement.execute("""
                        CREATE TABLE agent_episodes (
                            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                            tenant_id VARCHAR(64) NOT NULL,
                            session_id VARCHAR(128),
                            task_summary VARCHAR(500) NOT NULL
                        )
                        """);
                statement.execute("""
                        INSERT INTO agent_episodes (tenant_id, session_id, task_summary)
                        VALUES ('t1', 's1', 'legacy one'), ('t1', 's1', 'legacy two')
                        """);
            }

            Context context = mock(Context.class);
            when(context.getConnection()).thenReturn(connection);
            V11__TaskScopedEpisodes migration = new V11__TaskScopedEpisodes();
            migration.migrate(context);
            migration.migrate(context);

            try (Statement statement = connection.createStatement();
                 ResultSet rows = statement.executeQuery("""
                         SELECT COUNT(*) AS row_count, COUNT(task_id) AS assigned_count
                           FROM agent_episodes
                          WHERE tenant_id = 't1' AND session_id = 's1'
                         """)) {
                rows.next();
                assertEquals(2, rows.getInt("row_count"));
                assertEquals(0, rows.getInt("assigned_count"));
            }
            try (Statement statement = connection.createStatement()) {
                statement.execute("""
                        INSERT INTO agent_episodes (tenant_id, session_id, task_id, task_summary)
                        VALUES ('t1', 's1', '7', 'task episode')
                        """);
                statement.execute("""
                        INSERT INTO agent_episodes (tenant_id, session_id, task_id, task_summary)
                        VALUES ('t1', 's1', '7', 'duplicate task episode')
                        """);
            } catch (Exception expected) {
                // The unique index must reject a second episode for the same task.
            }

            try (Statement statement = connection.createStatement();
                 ResultSet rows = statement.executeQuery("""
                         SELECT COUNT(*) AS row_count
                           FROM agent_episodes
                          WHERE tenant_id = 't1' AND session_id = 's1' AND task_id = '7'
                         """)) {
                rows.next();
                assertEquals(1, rows.getInt("row_count"));
            }
        }
    }
}
